//! Packing equivalence is checked against the pinned engine's own singleton exporter.
use super::*;
use loro::{ExportMode, IdSpan, LoroDoc};
type Result<T = ()> = std::result::Result<T, Box<dyn std::error::Error>>;

fn hash(writer: u64, from: i32, through: i32, input: &[JsonChange]) -> Result<String> {
    Ok(changes("room", "schema", 13, writer, from, through, input)?)
}

#[test]
fn atoms_match_engine_singletons_for_unicode_lists_maps_and_both_delete_directions() -> Result {
    let doc = LoroDoc::new();
    doc.set_peer_id(101)?;
    let text = doc.get_text("text");
    text.insert(0, "A🙂e\u{301}日本語xyz")?;
    doc.get_list("list").insert(0, "one")?;
    doc.get_list("list").insert(1, "two")?;
    doc.get_list("list").insert(2, "three")?;
    doc.get_map("map").insert("key", "value")?;
    let movable = doc.get_movable_list("movable");
    movable.insert(0, "first")?;
    movable.insert(1, "second")?;
    movable.insert(2, "third")?;
    movable.mov(0, 2)?;
    movable.set(0, "changed")?;
    movable.delete(1, 2)?;
    let tree = doc.get_tree("tree");
    let parent = tree.create(loro::TreeParentId::Root)?;
    let child = tree.create(parent)?;
    tree.mov(child, loro::TreeParentId::Root)?;
    tree.delete(parent)?;
    doc.config_default_text_style(Some(loro::StyleConfig { expand: loro::ExpandType::After }));
    text.mark(0..2, "bold", true)?;
    doc.commit();
    // Forward sequential deletes coalesce without advancing their positions.
    text.delete(0, 2)?;
    text.delete(0, 1)?;
    doc.get_list("list").delete(0, 2)?;
    doc.commit();
    // Backspace-style deletes can coalesce in reverse operation order.
    text.delete(text.len_unicode() - 1, 1)?;
    text.delete(text.len_unicode() - 1, 1)?;
    doc.commit();
    let through = doc.state_vv().get(&101).copied().ok_or("head")?;
    let source = doc.export_json_in_id_span(IdSpan::new(101, 0, through));
    assert!(source.iter().flat_map(|c| &c.ops).any(
        |op| matches!(&op.content, JsonOpContent::Text(JsonTextOp::Delete { len, .. }) if *len < -1)
    ));
    let singletons = (0..through)
        .flat_map(|counter| doc.export_json_in_id_span(IdSpan::new(101, counter, counter + 1)))
        .collect::<Vec<_>>();
    assert_eq!(hash(101, 0, through, &source)?, hash(101, 0, through, &singletons)?);
    let receiver = LoroDoc::new();
    receiver.import(&doc.export(ExportMode::all_updates())?)?;
    assert_eq!(
        hash(101, 0, through, &source)?,
        hash(101, 0, through, &receiver.export_json_in_id_span(IdSpan::new(101, 0, through)))?
    );
    // Slicing within an insertion or deletion must also be canonical.
    for from in 0..through {
        for end in from..=through {
            let grouped = doc.export_json_in_id_span(IdSpan::new(101, from, end));
            let atoms = (from..end)
                .flat_map(|counter| {
                    doc.export_json_in_id_span(IdSpan::new(101, counter, counter + 1))
                })
                .collect::<Vec<_>>();
            assert_eq!(
                hash(101, from, end, &grouped)?,
                hash(101, from, end, &atoms)?,
                "{from}..{end}"
            );
        }
    }
    Ok(())
}

#[test]
fn changed_payload_clock_dependency_and_binding_never_share_a_lineage() -> Result {
    let doc = LoroDoc::new();
    doc.set_peer_id(101)?;
    doc.get_text("text").insert(0, "abc")?;
    doc.commit();
    let original = doc.export_json_in_id_span(IdSpan::new(101, 0, 3));
    let digest = hash(101, 0, 3, &original)?;
    // Independently generated by Node's SHA-256 over sorted JSON records with
    // unsigned big-endian u64 byte lengths. Freezes the version-two byte contract.
    assert_eq!(digest, "sha256:95da466f1c9264799ab31111b67860593b5674b886fd86a6a33ee33cacdb92dd");
    for mutation in 0..5 {
        let mut changed = original.clone();
        match mutation {
            0 => changed[0].lamport += 1,
            1 => changed[0].deps.push(ID::new(202, 4)),
            2 => {
                changed[0].ops[0].container =
                    loro::ContainerID::new_root("other", loro::ContainerType::Text);
            }
            3 => {
                changed[0].ops[0].content =
                    JsonOpContent::Text(JsonTextOp::Insert { pos: 0, text: "abd".into() });
            }
            _ => {
                changed[0].ops[0].content =
                    JsonOpContent::Text(JsonTextOp::Insert { pos: 1, text: "abc".into() });
            }
        }
        assert_ne!(hash(101, 0, 3, &changed)?, digest);
    }
    assert_ne!(changes("other", "schema", 13, 101, 0, 3, &original)?, digest);
    assert_ne!(changes("room", "other", 13, 101, 0, 3, &original)?, digest);
    assert_ne!(changes("room", "schema", 12, 101, 0, 3, &original)?, digest);
    let mut metadata = original.clone();
    metadata[0].timestamp = 999;
    metadata[0].msg = Some("nonsemantic commit metadata".into());
    assert_eq!(hash(101, 0, 3, &metadata)?, digest);
    assert!(hash(202, 0, 3, &original).is_err());
    assert!(hash(101, 0, 4, &original).is_err());
    assert!(hash(101, 1, 3, &original).is_err());
    Ok(())
}
