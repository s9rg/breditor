import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {mkdir, mkdtemp, readFile, realpath, rm, writeFile} from "node:fs/promises";
import {tmpdir} from "node:os";
import {join} from "node:path";
import test from "node:test";
import {retainNestedListFailure, retainNestedListReplayFailure, verifyFailureBundle} from "./retain-nested-list-failure.mjs";
import {prepareRetainedNestedLayoutTrace} from "./prepare-retained-nested-layout-trace.mjs";

const hash = value => createHash("sha256").update(value).digest("hex");
test("derived trace keeps control evidence and every non-script asset unchanged", async t => {
  const root = await realpath(await mkdtemp(join(tmpdir(), "breditor-derived-trace-test-")));
  t.after(() => rm(root, {recursive: true, force: true}));
  const source = join(root, "original");
  await mkdir(join(source, "bundle/assets"), {recursive: true});
  const script = `function layout(v,m,count,total){if(count>64)return null;const kind="breditor/bullet-list",item="breditor/list-item";let next=1;if(count!==1)return false;return next===total?{shapes:[],textBlocks:[]}:null;}`;
  const html = "<script type='module' src='/assets/main.js'></script>";
  const wasm = Buffer.from([0,97,115,109]);
  await writeFile(join(source, "bundle/index.html"), html);
  await writeFile(join(source, "bundle/assets/main.js"), script);
  await writeFile(join(source, "bundle/assets/test.wasm"), wasm);
  const original = Buffer.from(JSON.stringify({status: "failed", fixture: source, browserName: "webkit", ownerRepetitions: 3,
    bundleAssets: {"main.js": hash(script), "test.wasm": hash(wasm)}, measurements: [{status: "failed"}]}));
  await writeFile(join(source, "measurement.json"), original);
  const control = await retainNestedListFailure(join(source, "measurement.json"), join(root, "retained"));
  const result = await prepareRetainedNestedLayoutTrace(join(control, "measurement.json"), join(root, "retained"));
  assert.ok(result.output !== control);
  assert.deepEqual(await readFile(join(control, "measurement.json")), original);
  assert.equal(await readFile(join(control, "bundle/assets/main.js"), "utf8"), script);
  assert.deepEqual(await readFile(join(result.output, "original-measurement.json")), original);
  assert.equal(await readFile(join(result.output, "bundle/index.html"), "utf8"), html);
  assert.deepEqual(await readFile(join(result.output, "bundle/assets/test.wasm")), wasm);
  const manifest = JSON.parse(await readFile(join(result.output, "retention.json")));
  const verified = await verifyFailureBundle(result.measurementPath, manifest);
  assert.equal(verified.source.status, "prepared-diagnostic-only");
  assert.deepEqual(verified.source.measurements, []);
  assert.equal(verified.source.releaseQualified, false);
  assert.equal(verified.source.retainedLayoutDerivation.sourceMeasurementSha256, hash(original));
  assert.equal(verified.source.retainedLayoutDerivation.originalAssetSha256, hash(script));
  const tracedBytes = await readFile(join(result.output, "bundle/assets/main.js"));
  const measurementBytes = await readFile(result.measurementPath);
  const manifestBytes = await readFile(join(result.output, "retention.json"));
  // Even coordinated updates to derived hashes cannot conceal changed caller code.
  const prefix = "const outsideChange=1;";
  const altered = Buffer.from(prefix + tracedBytes.toString("utf8"));
  const alteredMeasurement = structuredClone(verified.source);
  alteredMeasurement.bundleAssets["main.js"] = hash(altered);
  alteredMeasurement.retainedLayoutDerivation.tracedAssetSha256 = hash(altered);
  alteredMeasurement.retainedLayoutDerivation.layout.start += prefix.length;
  alteredMeasurement.retainedLayoutDerivation.layout.tracedEnd += prefix.length;
  const alteredMeasurementBytes = Buffer.from(JSON.stringify(alteredMeasurement));
  const alteredManifest = {...manifest, measurementSha256: hash(alteredMeasurementBytes)};
  await writeFile(join(result.output, "bundle/assets/main.js"), altered);
  await writeFile(result.measurementPath, alteredMeasurementBytes);
  await assert.rejects(verifyFailureBundle(result.measurementPath, alteredManifest), /outside retained layout changed/);
  await writeFile(join(result.output, "bundle/assets/main.js"), tracedBytes);
  await writeFile(result.measurementPath, measurementBytes);
  await writeFile(join(result.output, "retention.json"), manifestBytes);
  await writeFile(join(result.output, "original-layout.js"), "changed original function");
  await assert.rejects(verifyFailureBundle(result.measurementPath, manifest));
  await writeFile(join(result.output, "original-layout.js"), verified.files["original-layout.js"]);
  const replayPath = join(result.output, "synthetic-failed-replay.json");
  await writeFile(replayPath, JSON.stringify({status: "failed", sourcePath: result.measurementPath,
    sourceSha256: hash(measurementBytes), indexSha256: hash(html), bundleAssets: verified.source.bundleAssets}));
  const retainedReplay = await retainNestedListReplayFailure(replayPath, result.measurementPath, join(root, "retained"), manifest);
  await writeFile(join(result.output, "bundle/assets/main.js"), "tampered");
  await assert.rejects(verifyFailureBundle(result.measurementPath, manifest));
  await writeFile(join(control, "measurement.json"), JSON.stringify({...JSON.parse(original), status: "measured"}));
  await assert.rejects(prepareRetainedNestedLayoutTrace(join(control, "measurement.json"), join(root, "retained")));
  // A failed derived replay keeps the entire provenance chain, not just assets.
  await rm(source, {recursive: true});
  await rm(control, {recursive: true});
  await rm(result.output, {recursive: true});
  const replayManifest = JSON.parse(await readFile(join(retainedReplay, "retention.json")));
  assert.equal(replayManifest.diagnosticDerivation, true);
  const standalone = await verifyFailureBundle(join(retainedReplay, "measurement.json"), replayManifest);
  assert.deepEqual(standalone.files["original-measurement.json"], original);
  assert.deepEqual(standalone.files["original-layout.js"], verified.files["original-layout.js"]);
});
