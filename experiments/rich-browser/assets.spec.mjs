test.beforeEach(async ({page}) => {
  await page.goto("/"); await expect(page.locator("#status")).toHaveText("Ready");
  await page.evaluate(async () => {
    window.assetName = `functional-assets:${crypto.randomUUID()}`;
    window.assetEvents = [];
    window.assets = await window.rich.RichAssetStore.open(window.assetName, {onChange: record => window.assetEvents.push(record)});
    window.rasterFile = async (mime = "image/png", color = "#ab3456") => {
      const canvas = document.createElement("canvas"); canvas.width = 3; canvas.height = 2;
      const paint = canvas.getContext("2d"); paint.fillStyle = color; paint.fillRect(0, 0, 3, 2);
      const blob = await new Promise(resolve => canvas.toBlob(resolve, mime));
      return new File([blob], "photo.png", {type: blob.type});
    };
    window.mountAssets = () => {
      const profile = window.rich.compileRichProfile(window.rich.wasm, JSON.stringify({format: "breditor/profile-bootstrap", formatVersion: 6, schema: {name: "example/rich-assets", version: 1}, extensions: []}));
      const binding = profile.descriptor(), canonical = value => Array.isArray(value) ? value.map(canonical)
        : value !== null && typeof value === "object" ? Object.fromEntries(Object.keys(value).sort().map(key => [key, canonical(value[key])])) : value;
      const core = profile.createEditor(JSON.stringify({format: "breditor/document", formatVersion: 2,
        schema: binding.schema, schemaFingerprint: binding.schemaFingerprint, root: canonical(window.rich.root)}));
      const root = document.createElement("main"); document.body.append(root);
      window.dom = window.rich.mountRichEditor(root, {core, resolveAsset: binding => window.assets.resolve(binding.asset),
        onError: error => { window.assetError = String(error); },
        onFiles: (files, position) => window.rich.insertImageFiles(window.dom, window.assets, files, position)});
      window.profile = profile;
    };
  });
});

