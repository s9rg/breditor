test("invalid MIME decode and configured budgets cannot admit partial records", async ({page}) => {
  const result = await page.evaluate(async () => {
    const file = await window.rasterFile();
    const limited = await window.rich.RichAssetStore.open(`${window.assetName}:limited`, {limits: {maxStoredBytes: file.size, maxPixels: 6}});
    const failure = async work => { try { await work(); return false; } catch { return true; } };
    const mime = await failure(() => window.assets.ingest(new Blob([file], {type: "image/jpeg"})));
    const invalid = await failure(() => window.assets.ingest(new Blob(["not an image"], {type: "image/png"})));
    const admitted = await limited.ingest(file), dedup = await limited.ingest(file);
    const budget = await failure(async () => limited.ingest(await window.rasterFile("image/png", "#112233")));
    const pixels = await window.rich.RichAssetStore.open(`${window.assetName}:pixels`, {limits: {maxPixels: 5}});
    const dimension = await failure(() => pixels.ingest(file));
    const result = {mime, invalid, budget, dimension, empty: (await window.assets.list()).length,
      limited: (await limited.list()).length, same: admitted.asset === dedup.asset};
    limited.close(); pixels.close(); return result;
  });
  expect(result).toEqual({mime: true, invalid: true, budget: true, dimension: true, empty: 0, limited: 1, same: true});
});

test("offline asset bytes and failed queue state survive actual reload and explicit retry", async ({page}) => {
  const saved = await page.evaluate(async () => {
    const asset = await window.assets.ingest(await window.rasterFile());
    await window.assets.flush(async () => { throw Error("private provider failure"); });
    return {name: window.assetName, asset: asset.asset, info: await window.assets.get(asset.asset)};
  });
  expect(saved.info).toMatchObject({status: "failed", attempts: 1, failure: "upload_failed"});
  expect(JSON.stringify(saved.info)).not.toContain("private provider");
  await page.reload(); await expect(page.locator("#status")).toHaveText("Ready");
  const recovered = await page.evaluate(async saved => {
    const store = await window.rich.RichAssetStore.open(saved.name);
    const previous = await store.get(saved.asset), blob = await store.blob(saved.asset);
    const url = await store.resolve(saved.asset), image = new Image(); image.src = url; await image.decode();
    await store.retry(saved.asset);
    await store.flush(async (record, bytes) => { if (record.asset !== saved.asset || bytes.size !== previous.bytes) throw Error("Wrong asset"); return "receipt:durable-local-test"; });
    const current = await store.get(saved.asset); store.close(); return {previous, current, size: blob.size, width: image.naturalWidth};
  }, saved);
  expect(recovered.previous).toEqual(saved.info); expect(recovered.size).toBe(saved.info.bytes); expect(recovered.width).toBe(3);
  expect(recovered.current).toMatchObject({status: "uploaded", attempts: 2, storageRef: "receipt:durable-local-test", failure: null});
});

test("cancel retry and late completion cannot overwrite the new upload epoch", async ({page}) => {
  const result = await page.evaluate(async () => {
    const asset = await window.assets.ingest(await window.rasterFile());
    let begin, finish; const started = new Promise(resolve => { begin = resolve; });
    const work = window.assets.flush(async () => { begin(); return new Promise(resolve => { finish = resolve; }); });
    await started;
    await window.assets.cancel(asset.asset); const cancelled = await window.assets.get(asset.asset);
    await work; // Cancellation releases the queue even if a provider ignores AbortSignal.
    await window.assets.retry(asset.asset); finish("receipt:obsolete");
    const stale = await window.assets.get(asset.asset);
    await window.assets.flush(async () => "receipt:current");
    return {cancelled, stale, current: await window.assets.get(asset.asset), retained: (await window.assets.blob(asset.asset)).size};
  });
  expect(result.cancelled.status).toBe("cancelled"); expect(result.stale).toMatchObject({status: "pending", storageRef: null});
  expect(result.current).toMatchObject({status: "uploaded", storageRef: "receipt:current", attempts: 2});
  expect(result.retained).toBe(result.current.bytes);
});

test("multiple file images insert in one exact history group after durable admission", async ({page}) => {
  const result = await page.evaluate(async () => {
    window.mountAssets(); const before = window.dom.view();
    const records = await window.rich.insertImageFiles(window.dom, window.assets,
      [await window.rasterFile(), await window.rasterFile("image/jpeg")], {parent: {kind: "document"}, before: null});
    const after = window.dom.view(), saved = window.dom.checkpointJson();
    window.dom.execute({kind: "undo"}); const undone = window.dom.view().documentJson;
    window.dom.execute({kind: "redo"}); const redone = window.dom.view().documentJson;
    const restored = window.profile.restoreEditor(saved); restored.execute({kind: "undo"});
    const recovered = restored.documentJson(); restored.dispose();
    return {before: before.documentJson, after: after.documentJson, undone, redone, recovered,
      increase: after.undoDepth - before.undoDepth, records};
  });
  expect(result.increase).toBe(1); expect(result.undone).toBe(result.before); expect(result.recovered).toBe(result.before); expect(result.redone).toBe(result.after);
  await expect(page.locator("figure img")).toHaveCount(3);
  await expect.poll(() => page.locator("figure img").last().evaluate(image => image.complete && image.naturalWidth)).toBe(3);
  expect(result.records.map(record => record.status)).toEqual(["pending", "pending"]);
});

test("late upload never revives a deleted image and undo still resolves retained bytes", async ({page}) => {
  const setup = await page.evaluate(async () => {
    window.mountAssets(); const records = await window.rich.insertImageFiles(window.dom, window.assets,
      [await window.rasterFile()], {parent: {kind: "document"}, before: null});
    const node = JSON.parse(window.dom.view().documentJson).root.children.at(-1);
    let begin; const started = new Promise(resolve => { begin = resolve; });
    window.uploading = window.assets.flush(async () => { begin(); return new Promise(resolve => { window.finishUpload = resolve; }); });
    await started; return {asset: records[0].asset, block: node.properties["breditor/block-id"]};
  });
  await page.evaluate(block => window.dom.execute({kind: "setSelection", selection: {kind: "node", block}}), setup.block);
  await page.getByRole("button", {name: "Delete selected node", exact: true}).click();
  const deleted = await page.evaluate(() => window.dom.view().documentJson);
  await page.evaluate(async () => { window.finishUpload("receipt:after-delete"); await window.uploading; });
  expect(await page.evaluate(() => window.dom.view().documentJson)).toBe(deleted);
  expect(await page.evaluate(asset => window.assets.get(asset), setup.asset)).toMatchObject({status: "uploaded"});
  await page.getByRole("button", {name: "Undo", exact: true}).click();
  await expect(page.locator("figure img")).toHaveCount(2);
  await expect.poll(() => page.locator("figure img").last().evaluate(image => image.complete && image.naturalWidth)).toBe(3);
});

test("file Paste and Drop event paths call the admitted asset host without duplicate insertion", async ({page}) => {
  await page.evaluate(async () => {
    window.mountAssets(); const file = await window.rasterFile();
    const paste = new ClipboardEvent("paste", {bubbles: true, cancelable: true, clipboardData: new DataTransfer()});
    paste.clipboardData.items.add(file); window.dom.surface.dispatchEvent(paste);
  });
  await expect(page.locator("figure")).toHaveCount(2);
  await page.evaluate(async () => {
    const data = new DataTransfer(); data.items.add(await window.rasterFile("image/jpeg"));
    window.dom.surface.dispatchEvent(new DragEvent("drop", {bubbles: true, cancelable: true, dataTransfer: data}));
  });
  await expect(page.locator("figure")).toHaveCount(3);
  const beforeCell=await page.evaluate(()=>window.dom.view().documentJson);
  await page.evaluate(async()=>{
    const cell={table:"t",row:"r",column:"c"};
    window.dom.execute({kind:"setSelection",selection:{kind:"grid",anchor:cell,focus:cell}});
    const paste=new ClipboardEvent("paste",{bubbles:true,cancelable:true,clipboardData:new DataTransfer()});
    paste.clipboardData.items.add(await window.rasterFile());window.dom.surface.dispatchEvent(paste);
  });
  await expect(page.locator('[data-rich-table="t"] figure')).toHaveCount(2);
  await expect(page.locator("figure")).toHaveCount(4);
  await page.getByRole("button",{name:"Undo",exact:true}).click();
  expect(await page.evaluate(()=>window.dom.view().documentJson)).toBe(beforeCell);
  expect(await page.evaluate(() => window.assets.list())).toHaveLength(2);
  expect(await page.evaluate(() => window.assetError ?? null)).toBeNull();
});
